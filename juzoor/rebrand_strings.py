def esc(s):
    return s.replace('&','&amp;').replace('<','&lt;').replace('>','&gt;')

def apply(path, updates, additions):
    txt = io.open(path, encoding='utf-8').read()
    for k,v in updates.items():
        pat = re.compile(r'<string name="%s">.*?</string>' % re.escape(k), re.S)
        new = '<string name="%s">%s</string>' % (k, esc(v))
        if pat.search(txt):
            txt = pat.sub(lambda m: new, txt, count=1)
        else:
            additions[k] = v
    block = []
    for k,v in additions.items():
        if ('name="%s"' % k) in txt:
            continue
        block.append('    <string name="%s">%s</string>' % (k, esc(v)))
    txt = txt.replace('</resources>', '\n'.join(block) + '\n</resources>')
    io.open(path,'w',encoding='utf-8').write(txt)
    print(path, 'updated', len(updates), 'added', len(block))

