package com.ramyelbanna.juzoor.engine;

import com.ramyelbanna.juzoor.core.LogManager;

import java.io.File;
import java.io.IOException;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.Comparator;
import java.util.List;
import java.util.Locale;

/**
 * Writes {@code PROJECT_TREE.txt}: a readable, size-annotated tree of every
 * artefact Juzoor produced, plus a roll-up so the user can see at a glance
 * where the space went.
 */
public final class ProjectTree {

    private static final int MAX_ENTRIES = 60000;

    private ProjectTree() {
    }

    public static File write(File projectRoot, LogSink log) throws IOException {
        StringBuilder b = new StringBuilder(16384);
        b.append("Juzoor 2.2 — project tree\n");
        b.append("Generated: ").append(new java.util.Date().toString()).append("\n");
        b.append("Root: ").append(projectRoot.getName()).append("\n\n");

        Counter counter = new Counter();
        walk(projectRoot, "", b, counter, 0);
        b.append('\n');
        b.append("Summary\n");
        b.append("-------\n");
        b.append("Files   : ").append(counter.files).append('\n');
        b.append("Folders : ").append(counter.dirs).append('\n');
        b.append("Size    : ").append(human(counter.bytes)).append('\n');
        if (counter.truncated) b.append("Note    : listing truncated at ").append(MAX_ENTRIES).append(" entries\n");

        File out = new File(projectRoot, "PROJECT_TREE.txt");
        ZipUtil.writeFile(out, b.toString());
        if (log != null) log.log(LogManager.INFO, "Project tree written: " + counter.files + " files, " + human(counter.bytes));
        return out;
    }

    /**
     * Writes {@code PROJECT_INDEX.md}: a navigable index of the recovered
     * project — packages, class counts, native libraries and a "start here"
     * guide so the tree can be opened in Android Studio without guessing.
     */
    public static File writeIndex(File projectRoot, ConversionResult r,
                                  List<DexStrings.Report> dexes,
                                  List<NativeAnalyzer.Report> natives,
                                  LogSink log) throws IOException {
        StringBuilder b = new StringBuilder(16384);
        b.append("# Project index — ")
                .append(r != null && r.appLabel != null && !r.appLabel.isEmpty() ? r.appLabel : "Recovered application")
                .append("\n\n");
        b.append("> Generated by **Juzoor 2.2** — APK to Source Code\n\n");
        b.append("| Property | Value |\n|---|---|\n");
        if (r != null) {
            b.append("| Package | `").append(nz(r.packageName)).append("` |\n");
            b.append("| Version | ").append(nz(r.versionName)).append(" (").append(r.versionCode).append(") |\n");
            // The index file itself is written after the caller's last count.
            b.append("| Files | ").append(r.fileCount + 1).append(" |\n");
            b.append("| Duration | ").append(r.durationMs / 1000).append("s |\n");
        }
        b.append('\n');

        /* ---- start here ---- */
        b.append("## Start here\n\n");
        b.append("1. `README.md` — what was recovered and how to open it.\n");
        b.append("2. `app/src/main/AndroidManifest.xml` — decoded manifest (entry activity, permissions).\n");
        b.append("3. `app/src/main/smali*/` — full Smali disassembly, one file per class.\n");
        b.append("4. `app/src/main/recovered/java|kotlin/` — reconstructed Java/Kotlin skeletons.\n");
        b.append("5. `app/src/main/res/` — decoded resources and layouts.\n");
        b.append("6. `app/src/main/jniLibs/` — native `.so` libraries per ABI.\n");
        b.append("7. `REPORT.md` — security and recovery report.\n");
        b.append("8. `PROJECT_TREE.txt` — complete size-annotated file tree.\n\n");

        /* ---- packages / classes ---- */
        b.append("## Packages\n\n");
        List<String> smaliRoots = new ArrayList<>();
        File main = new File(projectRoot, "app/src/main");
        File[] top = main.isDirectory() ? main.listFiles() : projectRoot.listFiles();
        if (top != null) {
            for (File f : top) {
                if (f.isDirectory() && (f.getName().equals("smali") || f.getName().startsWith("smali_"))) {
                    smaliRoots.add(f.getName());
                }
            }
        }
        java.util.TreeMap<String, Integer> packages = new java.util.TreeMap<>();
        int totalClasses = 0;
        for (String root : smaliRoots) {
            File dir = new File(main, root);
            List<File> files = new ArrayList<>();
            collectSmali(dir, files);
            for (File f : files) {
                totalClasses++;
                String rel = f.getAbsolutePath().substring(dir.getAbsolutePath().length() + 1);
                rel = rel.replace(File.separatorChar, '/');
                int slash = rel.lastIndexOf('/');
                String pkg = slash < 0 ? "(default)" : rel.substring(0, slash).replace('/', '.');
                Integer c = packages.get(pkg);
                packages.put(pkg, c == null ? 1 : c + 1);
            }
        }
        b.append("| Package | Classes |\n|---|---|\n");
        int shownPkg = 0;
        for (java.util.Map.Entry<String, Integer> e : packages.entrySet()) {
            if (shownPkg++ >= 300) { b.append("| … | ").append(packages.size() - 300).append(" more packages |\n"); break; }
            b.append("| `").append(e.getKey()).append("` | ").append(e.getValue()).append(" |\n");
        }
        b.append("\n**Total classes:** ").append(totalClasses).append("\n\n");

        /* ---- DEX string recovery ---- */
        if (dexes != null && !dexes.isEmpty()) {
            b.append("## DEX string recovery\n\n");
            b.append("| DEX | Strings | Encoded | Recovered | Keys mined |\n|---|---|---|---|---|\n");
            for (DexStrings.Report d : dexes) {
                b.append("| ").append(nz(d.name)).append(" | ").append(d.total).append(" | ")
                        .append(d.encoded).append(" | ").append(d.recovered).append(" | ")
                        .append(d.keysMined).append(" |\n");
            }
            b.append('\n');
        }

        /* ---- native libraries ---- */
        if (natives != null && !natives.isEmpty()) {
            b.append("## Native libraries\n\n");
            b.append("| Library | ABI | Bits | UPX | Unpacked |\n|---|---|---|---|---|\n");
            for (NativeAnalyzer.Report n : natives) {
                if (n == null) continue;
                b.append("| ").append(nz(n.name)).append(" | ").append(nz(n.abi)).append(" | ")
                        .append(n.is64 ? 64 : 32).append(" | ").append(n.upxDetected ? "yes" : "no")
                        .append(" | ").append(n.upxUnpacked ? "yes" : "no").append(" |\n");
            }
            b.append('\n');
        }

        File out = new File(projectRoot, "PROJECT_INDEX.md");
        ZipUtil.writeFile(out, b.toString());
        if (log != null) log.log(LogManager.INFO, "Project index written: " + totalClasses + " classes, " + packages.size() + " packages");
        return out;
    }

    private static void collectSmali(File dir, List<File> out) {
        File[] children = dir.listFiles();
        if (children == null) return;
        for (File f : children) {
            if (f.isDirectory()) collectSmali(f, out);
            else if (f.getName().endsWith(".smali")) out.add(f);
        }
    }

    private static String nz(String s) {
        return s == null ? "" : s;
    }

    private static void walk(File dir, String prefix, StringBuilder b, Counter c, int depth) {
        File[] children = dir.listFiles();
        if (children == null) return;
        List<File> list = new ArrayList<>(Arrays.asList(children));
        list.sort(new Comparator<File>() {
            @Override
            public int compare(File a, File b) {
                if (a.isDirectory() != b.isDirectory()) return a.isDirectory() ? -1 : 1;
                return a.getName().compareToIgnoreCase(b.getName());
            }
        });
        for (int i = 0; i < list.size(); i++) {
            if (c.entries++ > MAX_ENTRIES) {
                c.truncated = true;
                return;
            }
            File f = list.get(i);
            boolean last = i == list.size() - 1;
            String branch = last ? "└── " : "├── ";
            if (f.isDirectory()) {
                c.dirs++;
                b.append(prefix).append(branch).append(f.getName()).append("/\n");
                if (depth < 40) walk(f, prefix + (last ? "    " : "│   "), b, c, depth + 1);
            } else {
                c.files++;
                c.bytes += f.length();
                b.append(prefix).append(branch).append(f.getName())
                        .append("  (").append(human(f.length())).append(")\n");
            }
        }
    }

    public static String human(long j) {
        if (j < 1024) return j + " B";
        double d = j / 1024.0d;
        if (d < 1024.0d) return String.format(Locale.US, "%.1f KB", d);
        double d2 = d / 1024.0d;
        return d2 < 1024.0d ? String.format(Locale.US, "%.1f MB", d2)
                : String.format(Locale.US, "%.2f GB", d2 / 1024.0d);
    }

    private static final class Counter {
        int files;
        int dirs;
        int entries;
        long bytes;
        boolean truncated;
    }
}
