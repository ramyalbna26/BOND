package com.ramyelbanna.juzoor.engine;

import com.ramyelbanna.juzoor.core.LogManager;

import java.io.File;
import java.io.IOException;
import java.util.List;
import java.util.Locale;

/** Produces REPORT.md and report.json for a finished conversion. */
public final class ReportWriter {

    private ReportWriter() {
    }

    public static void write(File projectRoot, ConversionResult r,
                             List<NativeAnalyzer.Report> natives,
                             List<DexStrings.Report> dexes,
                             List<DartStrings.Report> dartStrings,
                             List<LibrarySupport.Library> libs,
                             LogSink log) throws IOException {
        File dir = new File(projectRoot, "analysis");
        dir.mkdirs();
        File md = new File(projectRoot, "REPORT.md");
        File json = new File(dir, "report.json");
        ZipUtil.writeFile(md, markdown(r, natives, dexes, dartStrings, libs));
        ZipUtil.writeFile(json, json(r, natives, dexes, dartStrings, libs));
        r.reportFile = md;
        r.reportJson = json;
        if (log != null) log.log(LogManager.SUCCESS, "Analysis report written: REPORT.md");
    }

    private static String markdown(ConversionResult r,
                                   List<NativeAnalyzer.Report> natives,
                                   List<DexStrings.Report> dexes,
                                   List<DartStrings.Report> dartStrings,
                                   List<LibrarySupport.Library> libs) {
        StringBuilder b = new StringBuilder(8192);
        b.append("# ").append(r.appLabel.isEmpty() ? "Recovered application" : r.appLabel).append("\n\n");
        b.append("> Generated by **Juzoor ").append(ConversionResult.GENERATOR_VERSION)
                .append("** — APK to Source Code\n\n");
        b.append("## Identity\n\n");
        b.append("| Property | Value |\n|---|---|\n");
        b.append("| Package | `").append(r.packageName).append("` |\n");
        b.append("| Version | ").append(r.versionName).append(" (").append(r.versionCode).append(") |\n");
        b.append("| Input | `").append(r.apkFile == null ? "?" : r.apkFile.getName()).append("` |\n");
        b.append("| Container | ").append(r.bundleKind)
                .append(r.isBundle ? " — " + (r.splitCount + 1) + " APKs merged" : "").append(" |\n");
        b.append("| Framework | ").append(r.frameworkLabel)
                .append(r.frameworkAssets > 0 ? " · " + r.frameworkAssets + " assets" : "").append(" |\n");
        b.append("| Duration | ").append(r.durationMs / 1000).append("s |\n\n");

        b.append("## Recovery summary\n\n");
        b.append("| Metric | Count |\n|---|---|\n");
        b.append("| Classes disassembled | ").append(r.classCount).append(" |\n");
        b.append("| DEX files | ").append(r.dexCount).append(" |\n");
        b.append("| Resource entries | ").append(r.resourceCount).append(" |\n");
        b.append("| Files written | ").append(r.fileCount).append(" |\n");
        b.append("| Native libraries | ").append(r.nativeLibCount).append(" |\n");
        b.append("| Libraries detected | ").append(r.libraryCount).append(" |\n");
        b.append("| Strings extracted | ").append(r.stringTotal).append(" (100% of DEX string table) |\n");
        b.append("| Strings encoded | ").append(r.stringEncrypted).append(" |\n");
        b.append("| Strings recovered | ").append(r.stringRecovered)
                .append(r.stringTotal > 0 ? " (" + percent(r.stringRecovered, r.stringTotal) + "% of table)" : "")
                .append(" |\n");
        b.append("| Strings decrypted | ").append(r.stringDecoded).append(" |\n");
        b.append("| Dart strings | ").append(r.dartStringCount).append(" |\n");
        b.append("| Java sources | ").append(r.javaFileCount)
                .append(" (").append(ConversionResult.JAVA_ENGINE).append(") |\n");
        b.append("| Kotlin API mirrors | ").append(r.kotlinFileCount).append(" |\n\n");

        if (AppFramework.FLUTTER.equals(r.framework)) {
            b.append("## Flutter / Dart\n\n");
            b.append("> Flutter application detected. The main program is written in Dart and\n")
                    .append("> is compiled into `libapp.so`. Dart snapshot strings are extracted in\n")
                    .append("> the `dart_strings/` folder; the Flutter asset tree is preserved under\n")
                    .append("> `app/src/main/assets/flutter_assets/`.\n\n");
            if (dartStrings.isEmpty()) {
                b.append("_No Dart snapshot library was found in this package._\n\n");
            } else {
                b.append("| Library | Markers | Snapshot regions | Snapshot bytes | Dart strings | UTF-16 | Text runs |\n");
                b.append("|---|---|---|---|---|---|---|\n");
                for (DartStrings.Report d : dartStrings) {
                    b.append("| `").append(esc(d.name)).append(d.abi.isEmpty() ? "" : " [" + esc(d.abi) + "]")
                            .append("` | ").append(d.markers)
                            .append(" | ").append(d.regions.size())
                            .append(" | ").append(d.snapshotBytes)
                            .append(" | ").append(d.dartStrings)
                            .append(" | ").append(d.utf16Strings)
                            .append(" | ").append(d.plainStrings).append(" |\n");
                }
                b.append("\nThe exact snapshot regions and offsets are recorded in\n")
                        .append("`analysis/dart_strings/` next to the extracted text files.\n\n");
            }
        }

        if (!r.packers.isEmpty()) {
            b.append("## Protectors / packers\n\n");
            for (String p : r.packers) b.append("- **").append(p).append("**\n");
            b.append("\nJuzoor carved every embedded payload it could find, recovered\n")
                    .append("XOR-obfuscated string tables, and statically unpacks UPX-compressed\n")
                    .append("ELF payloads without root (see the UPX section below). Only code\n")
                    .append("protected by a custom encrypted VM still needs a runtime dump.\n\n");
        }

        /* ---- static UPX unpack results ---- */
        boolean anyUpx = false;
        for (NativeAnalyzer.Report n : natives) {
            if (n != null && n.upxDetected) { anyUpx = true; break; }
        }
        if (anyUpx) {
            b.append("## UPX static unpacking\n\n");
            b.append("| Library | Detected | Unpacked | Method | Filter | Blocks | Bytes | Output |\n");
            b.append("|---|---|---|---|---|---|---|---|\n");
            for (NativeAnalyzer.Report n : natives) {
                if (n == null || !n.upxDetected) continue;
                String out = n.upxFile == null ? "—" : n.upxFile.getName();
                b.append("| ").append(esc(n.name)).append(" | yes | ")
                        .append(n.upxUnpacked ? "yes" : "no").append(" | ")
                        .append(esc(n.upxMethod == null || n.upxMethod.isEmpty() ? "—" : n.upxMethod)).append(" | ")
                        .append(esc(n.upxFilter == null || n.upxFilter.isEmpty() ? "—" : n.upxFilter)).append(" | ")
                        .append(n.upxBlocks).append(" | ").append(n.upxBytes).append(" | ")
                        .append(esc(out)).append(" |\n");
                if (!n.upxUnpacked && n.upxError != null && !n.upxError.isEmpty()) {
                    b.append("\n> ").append(esc(n.name)).append(": ").append(esc(n.upxError)).append("\n");
                }
            }
            b.append("\nUnpacked payloads are written under `analysis/native/unpacked/` as\n")
                    .append("`.payload.bin` and their printable strings are merged into the\n")
                    .append("native string table. The payload is not relinked into a runnable\n")
                    .append("library because the UPX loader's relocation/filter metadata is\n")
                    .append("not present in the compressed blocks.\n\n");
        }

        b.append("## Native libraries\n\n");
        if (natives.isEmpty()) {
            b.append("_No `.so` files in this application._\n\n");
        } else {
            b.append("| Library | ABI | Sections | Symbols | JNI exports | Strings | UTF-16 | Decoded | XOR | Carved |\n");
            b.append("|---|---|---|---|---|---|---|---|---|---|\n");
            for (NativeAnalyzer.Report n : natives) {
                b.append("| `").append(n.name).append("` | ").append(n.abi)
                        .append(" | ").append(n.sections.size())
                        .append(" | ").append(n.symbolCount)
                        .append(" | ").append(n.jniExports.size())
                        .append(" | ").append(n.stringCount)
                        .append(" | ").append(n.utf16Strings)
                        .append(" | ").append(n.decodedStrings)
                        .append(" | ").append(n.xorKey >= 0 ? "0x" + Integer.toHexString(n.xorKey) : "—")
                        .append(" | ").append(n.carved.size())
                        .append(" |\n");
            }
            b.append('\n');
            for (NativeAnalyzer.Report n : natives) {
                if (n.jniExports.isEmpty() && n.crypto.isEmpty() && n.carved.isEmpty()) continue;
                b.append("### `").append(n.name).append("`\n\n");
                if (!n.crypto.isEmpty()) b.append("- Crypto: ").append(String.join(", ", n.crypto)).append('\n');
                if (!n.jniExports.isEmpty()) {
                    b.append("- JNI exports (").append(n.jniExports.size()).append("):\n");
                    int limit = Math.min(25, n.jniExports.size());
                    for (int i = 0; i < limit; i++) b.append("  - `").append(n.jniExports.get(i)).append("`\n");
                    if (n.jniExports.size() > limit) b.append("  - … ").append(n.jniExports.size() - limit).append(" more\n");
                }
                for (NativeAnalyzer.Carved c : n.carved) {
                    b.append("- Carved **").append(c.kind).append("** at `0x")
                            .append(Long.toHexString(c.offset)).append("` (").append(c.size).append(" bytes)\n");
                }
                b.append('\n');
            }
        }

        b.append("## DEX string recovery\n\n");
        if (dexes.isEmpty()) {
            b.append("_String analysis disabled._\n\n");
        } else {
            b.append("| DEX | Extracted | Readable | Encoded | Decoded | Recovered | Hints | Raw byte-runs |\n");
            b.append("|---|---|---|---|---|---|---|---|\n");
            for (DexStrings.Report d : dexes) {
                b.append("| `").append(d.name).append("` | ").append(d.total)
                        .append(" / ").append(d.total).append(" (100%)")
                        .append(" | ").append(d.readable).append(" | ").append(d.encoded)
                        .append(" | ").append(d.recovered)
                        .append(" | ").append(d.resolved)
                        .append(" | ").append(d.hints)
                        .append(" | ").append(d.rawStrings).append(" |\n");
            }
            b.append('\n');
        }

        b.append("## Libraries\n\n");
        if (libs.isEmpty()) {
            b.append("_No known third-party libraries detected._\n\n");
        } else {
            b.append("| Library | Classes | Gradle coordinate |\n|---|---|---|\n");
            for (LibrarySupport.Library l : libs) {
                b.append("| ").append(l.name).append(" | ").append(l.hits)
                        .append(" | ").append(l.coordinate.isEmpty() ? "—" : "`" + l.coordinate + "`")
                        .append(" |\n");
            }
            b.append('\n');
        }

        if (r.security != null) {
            SecurityAnalyzer.Report s = r.security;
            b.append("## Security analysis\n\n");
            b.append("| Metric | Value |\n|---|---|\n");
            b.append("| Risk score | **").append(s.riskScore).append("/100** (").append(s.riskLabel()).append(") |\n");
            b.append("| Findings | ").append(s.total()).append(" |\n");
            b.append("| Critical / High / Medium / Low | ").append(s.critical).append(" / ")
                    .append(s.high).append(" / ").append(s.medium).append(" / ").append(s.low).append(" |\n");
            b.append("| Trackers & ad SDKs | ").append(s.trackers.size()).append(" |\n");
            b.append("| Hardcoded secrets | ").append(s.secrets.size()).append(" |\n");
            b.append("| Files scanned | ").append(s.filesScanned).append(" |\n\n");

            if (!s.trackers.isEmpty()) {
                b.append("### Trackers / advertising SDKs\n\n");
                for (String t : s.trackers) b.append("- ").append(t).append('\n');
                b.append('\n');
            }
            if (!s.secrets.isEmpty()) {
                b.append("### Hardcoded secrets\n\n");
                b.append("```\n");
                for (String secret : s.secrets) b.append(secret).append('\n');
                b.append("```\n\n");
            }
            if (!s.findings.isEmpty()) {
                b.append("### Findings\n\n");
                b.append("| Severity | Category | Title | Location |\n|---|---|---|---|\n");
                for (SecurityAnalyzer.Finding f : s.findings) {
                    b.append("| ").append(f.severity).append(" | ").append(esc(f.category))
                            .append(" | ").append(esc(f.title)).append(" | `").append(esc(f.location)).append("` |\n");
                }
                b.append('\n');
            }
        }

        if (!r.warnings.isEmpty()) {
            b.append("## Warnings\n\n");
            for (String w : r.warnings) b.append("- ").append(w).append('\n');
            b.append('\n');
        }

        b.append("## Project layout\n\n");
        b.append("```\n");
        b.append("app/src/main/AndroidManifest.xml   decoded manifest\n");
        b.append("app/src/main/res/                  decoded values + raw resources\n");
        b.append("app/src/main/assets/               original assets\n");
        b.append("app/src/main/jniLibs/<abi>/        native libraries\n");
        b.append("app/src/main/smali*/               disassembled Dalvik bytecode\n");
        b.append("app/src/main/recovered/java/    real decompiled Java (Jadx)\n");
        b.append("app/src/main/recovered/kotlin/  Kotlin API mirrors (not compiled)\n");
        b.append("analysis/native/                   ELF reports, strings, carved payloads\n");
        b.append("analysis/strings/                  DEX string tables and decoded entries\n");
        if (AppFramework.FLUTTER.equals(r.framework)) {
            b.append("dart_strings/                      Dart snapshot strings from libapp.so\n");
        }
        b.append("analysis/libraries.json            detected dependencies\n");
        b.append("```\n\n");
        b.append("## Building\n\n");
        b.append("```bash\n./gradlew assembleDebug\n```\n\n");
        b.append("Open the folder in Android Studio for the full IDE experience. The manifest,\n")
                .append("resources and native libraries are already in the standard Gradle layout.\n\n");
        b.append("---\n\n© 2027 Ramy El-Banna — Juzoor™\n");
        return b.toString();
    }

    private static int percent(int value, int total) {
        if (total <= 0) return 0;
        return (int) Math.round(value * 100.0d / total);
    }

    private static String esc(String s) {
        if (s == null) return "";
        return s.replace("|", "\\|").replace("\n", " ");
    }

    private static String jsonEsc(String s) {
        if (s == null) return "";
        return s.replace("\\", "\\\\").replace("\"", "\\\"")
                .replace("\n", "\\n").replace("\r", "").replace("\t", "\\t");
    }

    private static String json(ConversionResult r,
                               List<NativeAnalyzer.Report> natives,
                               List<DexStrings.Report> dexes,
                               List<DartStrings.Report> dartStrings,
                               List<LibrarySupport.Library> libs) {
        StringBuilder b = new StringBuilder(8192);
        b.append("{\n");
        b.append("  \"generator\": \"Juzoor\",\n");
        b.append("  \"version\": \"" + ConversionResult.GENERATOR_VERSION + "\",\n");
        b.append("  \"package\": \"").append(jsonEsc(r.packageName)).append("\",\n");
        b.append("  \"label\": \"").append(jsonEsc(r.appLabel)).append("\",\n");
        b.append("  \"versionName\": \"").append(jsonEsc(r.versionName)).append("\",\n");
        b.append("  \"versionCode\": ").append(r.versionCode).append(",\n");
        b.append("  \"bundle\": ").append(r.isBundle).append(",\n");
        b.append("  \"bundleKind\": \"").append(jsonEsc(r.bundleKind)).append("\",\n");
        b.append("  \"framework\": {\"kind\": \"").append(jsonEsc(r.framework))
                .append("\", \"label\": \"").append(jsonEsc(r.frameworkLabel))
                .append("\", \"assets\": ").append(r.frameworkAssets).append("},\n");
        b.append("  \"splits\": ").append(r.splitCount).append(",\n");
        b.append("  \"classes\": ").append(r.classCount).append(",\n");
        b.append("  \"dexFiles\": ").append(r.dexCount).append(",\n");
        b.append("  \"resources\": ").append(r.resourceCount).append(",\n");
        b.append("  \"files\": ").append(r.fileCount).append(",\n");
        b.append("  \"nativeLibraries\": ").append(r.nativeLibCount).append(",\n");
        b.append("  \"packers\": [");
        for (int i = 0; i < r.packers.size(); i++) {
            if (i > 0) b.append(", ");
            b.append('"').append(jsonEsc(r.packers.get(i))).append('"');
        }
        b.append("],\n");
        b.append("  \"strings\": {\"total\": ").append(r.stringTotal)
                .append(", \"extracted\": ").append(r.stringTotal)
                .append(", \"readable\": ").append(r.stringReadable)
                .append(", \"encoded\": ").append(r.stringEncrypted)
                .append(", \"decoded\": ").append(r.stringDecoded)
                .append(", \"recovered\": ").append(r.stringRecovered).append("},\n");
        b.append("  \"dartStrings\": {\"total\": ").append(r.dartStringCount)
                .append(", \"libraries\": ").append(r.dartLibraryCount).append("},\n");
        b.append("  \"source\": {\"engine\": \"").append(jsonEsc(ConversionResult.JAVA_ENGINE))
                .append("\", \"javaFiles\": ").append(r.javaFileCount)
                .append(", \"kotlinFiles\": ").append(r.kotlinFileCount)
                .append(", \"skipped\": ").append(r.javaSkippedCount).append("},\n");
        b.append("  \"libraries\": ").append(LibrarySupport.toJson(libs)).append(",\n");
        if (r.security != null) {
            b.append("  \"security\": {\"riskScore\": ").append(r.security.riskScore)
                    .append(", \"findings\": ").append(r.security.total())
                    .append(", \"critical\": ").append(r.security.critical)
                    .append(", \"high\": ").append(r.security.high)
                    .append(", \"medium\": ").append(r.security.medium)
                    .append(", \"low\": ").append(r.security.low)
                    .append(", \"trackers\": ").append(r.security.trackers.size())
                    .append(", \"secrets\": [");
            for (int i = 0; i < r.security.secrets.size(); i++) {
                if (i > 0) b.append(", ");
                b.append('"').append(jsonEsc(r.security.secrets.get(i))).append('"');
            }
            b.append("]},\n");
        }
        b.append("  \"native\": [");
        for (int i = 0; i < natives.size(); i++) {
            if (i > 0) b.append(',');
            NativeAnalyzer.Report n = natives.get(i);
            b.append("\n    {\"name\": \"").append(n.name).append("\", \"abi\": \"").append(n.abi)
                    .append("\", \"sections\": ").append(n.sections.size())
                    .append(", \"jniExports\": ").append(n.jniExports.size())
                    .append(", \"strings\": ").append(n.stringCount)
                    .append(", \"xorKey\": ").append(n.xorKey)
                    .append(", \"recovered\": ").append(n.recovered.size())
                    .append(", \"carved\": ").append(n.carved.size())
                    .append(", \"packers\": ").append(n.packers.size()).append('}');
        }
        b.append("\n  ],\n  \"dex\": [");
        for (int i = 0; i < dexes.size(); i++) {
            if (i > 0) b.append(',');
            DexStrings.Report d = dexes.get(i);
            b.append("\n    {\"name\": \"").append(d.name).append("\", \"total\": ").append(d.total)
                    .append(", \"extracted\": ").append(d.total)
                    .append(", \"readable\": ").append(d.readable)
                    .append(", \"encoded\": ").append(d.encoded)
                    .append(", \"obfuscated\": ").append(d.obfuscated)
                    .append(", \"rawStrings\": ").append(d.rawStrings)
                    .append(", \"hints\": ").append(d.hints)
                    .append(", \"resolved\": ").append(d.resolved)
                    .append(", \"recovered\": ").append(d.recovered)
                    .append(", \"decryptors\": ").append(d.decryptorSites).append('}');
        }
        b.append("\n  ],\n  \"dart\": [");
        for (int i = 0; i < dartStrings.size(); i++) {
            if (i > 0) b.append(',');
            DartStrings.Report d = dartStrings.get(i);
            b.append("\n    {\"name\": \"").append(jsonEsc(d.name))
                    .append("\", \"markers\": ").append(d.markers)
                    .append(", \"regions\": ").append(d.regions.size())
                    .append(", \"snapshotBytes\": ").append(d.snapshotBytes)
                    .append(", \"strings\": ").append(d.total)
                    .append(", \"utf16\": ").append(d.utf16Strings).append('}');
        }
        b.append("\n  ],\n");
        b.append("  \"durationMs\": ").append(r.durationMs).append("\n}\n");
        return b.toString();
    }
}
